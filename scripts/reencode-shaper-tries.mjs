// One-off: rebuild the fontkit shaper tries (trie.ts = Arabic joining,
// trieIndic.ts, trieUse.ts) in the format read by
// src/vendors/unicode-properties/UnicodeTrie.ts:
//
//   base64( zlib( u32le highStart | u32le errorValue | u32le data[] ) )
//
// Background (see the git history of this script for the investigation):
// the blobs copied in by the TypeScript migration (34d8b07f) were serialized
// by the unicode-trie 0.3 builder that @pdf-lib/fontkit used: a 12-byte
// BIG-endian header (highStart, errorValue, uncompressedLength) followed by
// the u32le data, deflated twice, then zlib'd again for embedding. The
// unicode-trie 2.x reader the shapers used at HEAD reads that header as
// little-endian, so highStart was garbage (0x1100 instead of 0x110000 for
// trie.ts/trieIndic.ts), breaking every supplementary-plane lookup. Worse,
// the blobs were mislabelled:
//   - trie.ts held the unicode-properties data trie (the same values as
//     src/vendors/unicode-properties/trie.json), not the Arabic joining trie;
//   - trieUse.ts held the Arabic joining trie (generate-data.js output);
//   - the real USE category trie was missing entirely.
// So this script:
//   - trie.ts      <- the Arabic trie found in the old trieUse.ts, checked
//                     against ArabicShaping.txt per generate-data.js;
//   - trieIndic.ts <- the old trieIndic.ts, with the BE header honoured;
//   - trieUse.ts   <- regenerated by gen-use-trie.mjs (gen-use.js port) from
//                     Unicode 12 data, the snapshot use.ts was built from.
// Every new blob is decoded independently and compared against its source
// for all code points 0..0x10FFFF before anything is written. Also writes
// the sample fixture used by tests/fontkit/shaperTries.spec.ts.
//
// Kept as a record of the conversion. Needs `unicode-trie` 2.x, which is no
// longer a dependency (temporarily `pnpm add -D unicode-trie@2` to re-run),
// and the UCD files in scripts/ucd-cache/9004b7fa6d (see gen-use-trie.mjs).
// Must run on the ORIGINAL blobs, i.e. the trie*.ts from before the commit
// that added this script.
// Run from the repo root:
//   node scripts/reencode-shaper-tries.mjs

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { unzlibSync, zlibSync } from 'fflate';
import { buildUseTrie } from './gen-use-trie.mjs';

const require = createRequire(import.meta.url);
const OldUnicodeTrie = require('unicode-trie');

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const shaperDir = join(root, 'src/fontkit/opentype/shapers');
const fixturePath = join(root, 'tests/fontkit/shaperTries.fixture.json');
const ucdDir = join(root, 'scripts/ucd-cache/9004b7fa6d');

// Must match INDEX_1_OFFSET in the vendored reader; the v2 reader derives it.
const VENDORED_INDEX_1_OFFSET = 0x840;

// Ranges sampled exhaustively in the test fixture (relevant scripts).
const FIXTURE_RANGES = [
  [0x0000, 0x007f], // ASCII
  [0x0600, 0x06ff], // Arabic
  [0x0700, 0x074f], // Syriac
  [0x07c0, 0x07ff], // NKo
  [0x0900, 0x0dff], // Devanagari .. Sinhala
  [0x0f00, 0x0fff], // Tibetan
  [0x1780, 0x17ff], // Khmer
  [0x1880, 0x18af], // Mongolian
  [0x1b00, 0x1b7f], // Balinese
  [0x200c, 0x200d], // ZWNJ/ZWJ
  [0xa840, 0xa87f], // Phags-pa
  [0xa980, 0xa9df], // Javanese
  [0xd7f0, 0xdc10], // around surrogates
  [0x10ac0, 0x10aff], // Manichaean
  [0x11000, 0x1107f], // Brahmi
  [0x1e900, 0x1e95f], // Adlam
];
const FIXTURE_STRIDE = 4099; // plus every 4099th code point

function fail(msg) {
  console.error(`reencode-shaper-tries: ${msg}`);
  process.exit(1);
}

function readBlob(file) {
  const src = readFileSync(join(shaperDir, file), 'utf8');
  const m = /^export default '([A-Za-z0-9+/=]+)';?\s*$/.exec(src);
  if (!m) fail(`${file}: unexpected file layout`);
  return m[1];
}

// Decode a unicode-trie 0.3 serialization (BE header). The payload is read
// with the 2.x constructor (same double-inflate + u32le data), then the
// header fields it misread as little-endian are replaced.
function loadOld(file, b64) {
  const outer = Buffer.from(unzlibSync(Buffer.from(b64, 'base64')));
  if (outer.length < 12) fail(`${file}: blob too short`);
  let trie;
  try {
    trie = new OldUnicodeTrie(new Uint8Array(outer));
  } catch (e) {
    fail(`${file}: could not decode as unicode-trie 0.3 (already converted?): ${e}`);
  }
  const misread = trie.highStart;
  trie.highStart = outer.readUInt32BE(0);
  trie.errorValue = outer.readUInt32BE(4);
  if (!(trie.data.length >= 0x820) || trie.highStart > 0x110000) {
    fail(`${file}: implausible trie (already converted?)`);
  }
  console.log(
    `${file}: header highStart 0x${trie.highStart.toString(16)} (HEAD's reader saw 0x${misread.toString(16)})`,
  );
  return { trie, misread };
}

function encodeNew(t) {
  const bytes = new Uint8Array(8 + t.data.length * 4);
  const view = new DataView(bytes.buffer);
  view.setUint32(0, t.highStart >>> 0, true);
  view.setUint32(4, t.errorValue >>> 0, true);
  for (let i = 0; i < t.data.length; i++) {
    view.setUint32(8 + i * 4, t.data[i], true);
  }
  return Buffer.from(zlibSync(bytes, { level: 9 })).toString('base64');
}

// Independent parse of the new format, mirroring the vendored reader,
// then evaluated with the reference lookup algorithm.
function loadNew(b64) {
  const raw = unzlibSync(Buffer.from(b64, 'base64'));
  if ((raw.length - 8) % 4 !== 0) fail('new blob payload not 4-byte aligned');
  const view = new DataView(raw.buffer, raw.byteOffset, raw.byteLength);
  const highStart = view.getUint32(0, true);
  const errorValue = view.getUint32(4, true);
  const data = new Uint32Array((raw.length - 8) / 4);
  for (let i = 0; i < data.length; i++) {
    data[i] = view.getUint32(8 + i * 4, true);
  }
  return new OldUnicodeTrie({ data, highStart, errorValue });
}

function compareAll(label, get1, get2, maxReport = 10) {
  let mismatches = 0;
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    const a = get1(cp);
    const b = get2(cp);
    if (a !== b || a === undefined) {
      if (mismatches++ < maxReport) {
        console.error(`${label}: U+${cp.toString(16)} ${a} vs ${b}`);
      }
    }
  }
  return mismatches;
}

function verify(file, srcTrie, newTrie) {
  let n = compareAll(file, (cp) => srcTrie.get(cp), (cp) => newTrie.get(cp));
  for (const cp of [-1, 0x110000, 0x7fffffff]) {
    if (srcTrie.get(cp) !== newTrie.get(cp)) {
      n++;
      console.error(`${file}: probe ${cp} differs`);
    }
  }
  if (n) fail(`${file}: ${n} mismatching code points`);
}

// Expected Arabic joining values per fontkit's generate-data.js.
function arabicReference() {
  const SC = {
    Non_Joining: 0, Left_Joining: 1, Right_Joining: 2, Dual_Joining: 3,
    Join_Causing: 3, ALAPH: 4, 'DALATH RISH': 5, Transparent: 6,
  };
  const JT = { U: 'Non_Joining', L: 'Left_Joining', R: 'Right_Joining', D: 'Dual_Joining', C: 'Join_Causing', T: 'Transparent' };
  const assigned = new Set();
  let rangeStart = -1;
  for (const line of readFileSync(join(ucdDir, 'UnicodeData.txt'), 'ascii').split('\n')) {
    if (!line) continue;
    const [hex, name] = line.split(';');
    const cp = parseInt(hex, 16);
    if (rangeStart >= 0) {
      for (let c = rangeStart; c <= cp; c++) assigned.add(c);
      rangeStart = -1;
    } else if (/<.+, First>/.test(name)) rangeStart = cp;
    else assigned.add(cp);
  }
  const map = new Map();
  for (const line of readFileSync(join(ucdDir, 'ArabicShaping.txt'), 'ascii').split('\n')) {
    if (!line || line[0] === '#') continue;
    const [hex, , jt, group] = line.replace(/\s*#.*$/, '').split(/\s*;\s*/);
    const cp = parseInt(hex, 16);
    if (!assigned.has(cp)) continue;
    const v = group === 'ALAPH' || group === 'DALATH RISH' ? SC[group] + 1 : SC[JT[jt]] + 1;
    map.set(cp, v);
  }
  return (cp) => map.get(cp) ?? 0;
}

function sampleCodePoints() {
  const set = new Set();
  for (const [lo, hi] of FIXTURE_RANGES) {
    for (let cp = lo; cp <= hi; cp++) set.add(cp);
  }
  for (let cp = 0; cp <= 0x10ffff; cp += FIXTURE_STRIDE) set.add(cp);
  set.add(0x10ffff);
  return [...set].sort((a, b) => a - b);
}

// sanity: the vendored reader hard-codes INDEX_1_OFFSET
if (2080 + 32 !== VENDORED_INDEX_1_OFFSET) fail('INDEX_1_OFFSET mismatch');

// --- sources ---------------------------------------------------------------
const oldTrieTs = loadOld('trie.ts', readBlob('trie.ts'));
const oldIndic = loadOld('trieIndic.ts', readBlob('trieIndic.ts'));
const oldUse = loadOld('trieUse.ts', readBlob('trieUse.ts'));

// The old trie.ts (unicode-properties packed data, not Arabic joining types)
// is discarded; see scripts/probe-old-trie-ts.mjs for the evidence.
void oldTrieTs;

const arabicRef = arabicReference();
{
  const n = compareAll('old trieUse.ts vs ArabicShaping', (cp) => oldUse.trie.get(cp), arabicRef);
  if (n) fail(`old trieUse.ts is not the Arabic joining trie (${n} mismatches)`);
  console.log('old trieUse.ts == Arabic joining trie (generate-data.js, Unicode 12): all code points');
}

const useGen = buildUseTrie(ucdDir).trie;

const targets = [
  ['trie.ts', oldUse.trie],
  ['trieIndic.ts', oldIndic.trie],
  ['trieUse.ts', useGen],
];

// HEAD behaviour, for the record.
{
  const head = new OldUnicodeTrie({
    data: oldIndic.trie.data,
    highStart: oldIndic.misread,
    errorValue: oldIndic.trie.errorValue,
  });
  const headIndicBroken = compareAll(
    'HEAD trieIndic',
    (cp) => oldIndic.trie.get(cp),
    (cp) => head.get(cp),
    0,
  );
  console.log(`HEAD trieIndic.ts: ${headIndicBroken} code points wrong due to the LE header misread`);
}

const cps = sampleCodePoints();
const results = [];
const fixture = { codePoints: cps, values: {} };

for (const [file, src] of targets) {
  const newB64 = encodeNew(src);
  const newTrie = loadNew(newB64);
  verify(file, src, newTrie);
  fixture.values[file] = cps.map((cp) => src.get(cp));
  results.push([file, newB64]);
  console.log(`${file}: verified 0x110000 code points`);
}

// Only write once all three verified.
for (const [file, newB64] of results) {
  writeFileSync(join(shaperDir, file), `export default '${newB64}';\n`);
  console.log(`${file}: wrote ${newB64.length} base64 chars`);
}
mkdirSync(dirname(fixturePath), { recursive: true });
writeFileSync(fixturePath, JSON.stringify(fixture) + '\n');
console.log(`wrote ${fixturePath} (${cps.length} code points)`);
