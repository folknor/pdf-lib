#!/usr/bin/env python3
"""Generate Unicode 3.2 SASLprep data from specifications, never host Unicode.

Run: python3 scripts/gen-password-prep.py
Sources are version-pinned UCD data and RFC 3454 (not third-party code).
"""
import hashlib
import json
from pathlib import Path
import re
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    'rfc': 'https://www.rfc-editor.org/rfc/rfc3454.txt',
    'ucd': 'https://www.unicode.org/Public/3.2-Update/UnicodeData-3.2.0.txt',
    'exclusions': 'https://www.unicode.org/Public/3.2-Update/CompositionExclusions-3.2.0.txt',
}
data = {key: urlopen(url).read() for key, url in SOURCES.items()}
rfc = data['rfc'].decode()
tables = {}
for name in ['B.1', 'B.2', 'C.1.1', 'C.1.2', 'C.2.1', 'C.2.2', 'C.3', 'C.4', 'C.5', 'C.6', 'C.7', 'C.8', 'C.9', 'D.1', 'D.2']:
    body = rfc.split('----- Start Table ' + name + ' -----')[1].split('----- End Table ' + name + ' -----')[0]
    entries = []
    for line in body.splitlines():
        match = re.match(r'\s*([0-9A-F]{4,6})(?:-([0-9A-F]{4,6}))?(?:;|\s*$)', line)
        if not match:
            continue
        lo = int(match[1], 16)
        if name == 'B.2':
            entries.append([lo, [int(c, 16) for c in line.split(';')[1].split()]])
        else:
            entries.append([lo, int(match[2], 16) if match[2] else lo])
    assert entries, name
    tables[name] = entries
excluded = {int(m[1], 16) for line in data['exclusions'].decode().splitlines() if (m := re.match(r'^([0-9A-F]+)', line))}
ccc, decomposition, composition = {}, {}, {}
for line in data['ucd'].decode().splitlines():
    fields = line.split(';')
    cp = int(fields[0], 16)
    if int(fields[3]):
        ccc[cp] = int(fields[3])
    parts = fields[5].split()
    if parts:
        canonical = not parts[0].startswith('<')
        decomposition[cp] = [int(p, 16) for p in parts if not p.startswith('<')]
        if canonical and len(parts) == 2 and cp not in excluded:
            composition[','.join(str(int(p, 16)) for p in parts)] = cp
# Singleton decompositions and nonstarter first elements are full composition exclusions.
composition = {k: v for k, v in composition.items() if int(k.split(',')[0]) not in ccc}
header = '// Generated by scripts/gen-password-prep.py; do not edit.\n'
for key, url in SOURCES.items():
    header += f'// {url}\n// SHA-256: {hashlib.sha256(data[key]).hexdigest()}\n'
output = header
for name, value, typ in [
    ('STRINGPREP_TABLES', tables, 'Record<string, ReadonlyArray<readonly [number, number]>>'),
    ('CASE_FOLDING_B2', dict(tables['B.2']), 'Record<number, readonly number[]>'),
    ('COMBINING_CLASS', ccc, 'Record<number, number>'),
    ('DECOMPOSITION', decomposition, 'Record<number, readonly number[]>'),
    ('COMPOSITION', composition, 'Record<string, number>'),
]:
    if name == 'STRINGPREP_TABLES':
        value = {k: v for k, v in value.items() if k != 'B.2'}
    output += f'export const {name}: {typ} = {json.dumps(value, separators=(",", ":"))};\n'
(ROOT / 'src/core/security/passwordPrepData.ts').write_text(output)
